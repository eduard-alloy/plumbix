package review

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/eduard-alloy/plumbix/internal/change"
	"github.com/eduard-alloy/plumbix/internal/validation"
)

// modelOutput is what the API's structured output returns.
type modelOutput struct {
	Outcome  validation.Outcome `json:"outcome"`
	Summary  string             `json:"summary"`
	Criteria []struct {
		ID       string            `json:"id"`
		Status   validation.Status `json:"status"`
		Reason   string            `json:"reason"`
		Evidence []string          `json:"evidence"`
	} `json:"criteria"`
	Findings []struct {
		Severity  string `json:"severity"`
		Message   string `json:"message"`
		Criterion string `json:"criterion"`
		File      string `json:"file"`
		Line      int    `json:"line"`
	} `json:"findings"`
	Risks []validation.Risk `json:"risks"`
}

func object(props map[string]any) map[string]any {
	req := make([]string, 0, len(props))
	for k := range props {
		req = append(req, k)
	}
	return map[string]any{"type": "object", "properties": props, "required": req, "additionalProperties": false}
}

func str() map[string]any                  { return map[string]any{"type": "string"} }
func enum(values ...string) map[string]any { return map[string]any{"type": "string", "enum": values} }
func list(item any) map[string]any         { return map[string]any{"type": "array", "items": item} }

// OutputSchema is the JSON schema sent as the structured output format. It
// avoids keywords structured outputs don't support; Plumbix checks the rest.
// criterionIDs, when given, is the only set of ids the model may use, so it
// cannot invent a criterion for a constraint or a risk.
func OutputSchema(criterionIDs []string) map[string]any {
	id := str()
	if len(criterionIDs) > 0 {
		id = enum(criterionIDs...)
	}
	return object(map[string]any{
		"outcome": enum("approve", "fix", "reject"),
		"summary": str(),
		"criteria": list(object(map[string]any{
			"id": id, "status": enum("met", "unmet", "unknown"), "reason": str(), "evidence": list(str()),
		})),
		"findings": list(object(map[string]any{
			"severity": enum("blocker", "major", "minor"), "message": str(), "criterion": str(),
			"file": str(), "line": map[string]any{"type": "integer", "description": "1-based line, or 0 when not tied to a line"},
		})),
		"risks": list(object(map[string]any{
			"area": str(), "message": str(), "human_required": map[string]any{"type": "boolean"},
		})),
	})
}

// excerptChars bounds how much model output an error quotes.
const excerptChars = 2000

func excerpt(raw []byte) string {
	if len(raw) > excerptChars {
		return string(raw[:excerptChars]) + "..."
	}
	return string(raw)
}

// ToVerdict converts the model's output into a checked verdict/v1.
func ToVerdict(raw []byte, criteria []change.Criterion, usage validation.Usage) (validation.Verdict, error) {
	var out modelOutput
	if err := json.Unmarshal(raw, &out); err != nil {
		return validation.Verdict{}, fmt.Errorf("model output is not valid JSON: %w; output was: %s", err, excerpt(raw))
	}
	v := validation.Verdict{Plumbix: validation.VerdictVersion, Outcome: out.Outcome, Summary: out.Summary, Usage: &usage}
	unmet := false
	counts := map[validation.Status]int{}
	known := map[string]bool{}
	for _, c := range criteria {
		known[c.ID] = true
	}
	seen := map[string]bool{}
	var dropped []string
	for _, c := range out.Criteria {
		// A criterion the change does not have, or one judged twice, must
		// not fail the whole review: keep the first judgment of each real
		// criterion and say what was left out.
		if !known[c.ID] || seen[c.ID] {
			dropped = append(dropped, c.ID)
			continue
		}
		seen[c.ID] = true
		cv := validation.CriterionVerdict{ID: c.ID, Status: c.Status, Reason: c.Reason, Evidence: c.Evidence}
		if strings.TrimSpace(cv.Reason) == "" {
			// A status the model didn't explain can't be trusted.
			cv.Status, cv.Reason = validation.Unknown, "the model gave no reason, so treated as unknown"
		}
		if cv.Status == validation.Met && len(cv.Evidence) == 0 {
			cv.Status = validation.Unknown
			cv.Reason += " (marked met with no evidence, so treated as unknown)"
		}
		if cv.Status == validation.Unmet {
			unmet = true
		}
		counts[cv.Status]++
		v.Criteria = append(v.Criteria, cv)
	}
	if strings.TrimSpace(v.Summary) == "" {
		v.Summary = fmt.Sprintf("(summary generated by Plumbix; the model gave none) %d met, %d unmet, %d unknown",
			counts[validation.Met], counts[validation.Unmet], counts[validation.Unknown])
	}
	if v.Outcome == validation.Approve && unmet {
		v.Outcome = validation.Fix
	}
	if len(dropped) > 0 {
		v.Summary += fmt.Sprintf(" (Plumbix dropped %d criterion entr%s the model added or repeated: %s)", len(dropped), map[bool]string{true: "y", false: "ies"}[len(dropped) == 1], strings.Join(dropped, ", "))
	}
	for _, f := range out.Findings {
		fd := validation.Finding{Severity: f.Severity, Message: f.Message, Criterion: f.Criterion, File: f.File}
		if f.Line > 0 {
			line := f.Line
			fd.Line = &line
		}
		v.Findings = append(v.Findings, fd)
	}
	v.Risks = out.Risks
	data, err := json.Marshal(v)
	if err != nil {
		return validation.Verdict{}, err
	}
	if _, err := validation.ParseVerdict(data, criteria); err != nil {
		return validation.Verdict{}, fmt.Errorf("model output breaks the verdict contract: %w; output was: %s", err, excerpt(raw))
	}
	return v, nil
}

// CriterionIDs lists the ids of a change's criteria, in order.
func CriterionIDs(criteria []change.Criterion) []string {
	ids := make([]string, 0, len(criteria))
	for _, c := range criteria {
		ids = append(ids, c.ID)
	}
	return ids
}
